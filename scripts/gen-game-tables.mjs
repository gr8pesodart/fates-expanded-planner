/**
 * Generates src/prototype/gameTables.ts from the installed data pack so the
 * prototype fixtures use real ids/numbers and wire up without translation.
 * Reads (never writes) src/data/packs/ugf-2.5.2.
 *
 *   node scripts/gen-game-tables.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pack = join(root, 'src', 'data', 'packs', 'ugf-2.5.2')

const readJson = (file) => JSON.parse(readFileSync(join(pack, file), 'utf8'))

const characters = readJson('characters.json')
const supports = readJson('supports.json')
const units = readJson('units.json').units
const classes = readJson('classes.json').classes
const skills = readJson('skills.json').skills

const CURATED = [
  'PID_プレイヤー男',
  'PID_プレイヤー女',
  'PID_リョウマ',
  'PID_カミラ',
  'PID_シノノメ',
  'PID_スズカゼ',
  'PID_サイゾウ',
  'PID_アクア',
  'PID_マークス',
  'PID_タクミ',
  'PID_ヒノカ',
  'PID_オボロ',
  'PID_ゼロ',
  'PID_ルーナ',
  'PID_キサラギ',
  'PID_ツバキ',
  'PID_セツナ',
  'PID_カンナ女',
]

const DLC_CLASS_MIN = 118
const DLC_CLASS_MAX = 127
const DLC_UNITS = new Set(['PID_アンナ'])

const decode = (raw) => {
  const u = raw >>> 0
  const pick = (v) => (v === 0xff ? null : v)
  const s = pick((u >>> 24) & 0xff)
  const a = pick((u >>> 16) & 0xff)
  const c = pick(u & 0xff)
  return { romantic: s !== null, s: s !== null, a: a !== null, fast: c !== null && c < 4 }
}

const supportRows = new Map()
for (const [ia, ib, raw] of supports.edges) {
  const a = characters[ia].id
  const b = characters[ib].id
  if (!CURATED.includes(a) && !CURATED.includes(b)) continue
  const info = decode(raw)
  if (!supportRows.has(a)) supportRows.set(a, [])
  if (!supportRows.has(b)) supportRows.set(b, [])
  supportRows.get(a).push([b, info.romantic, info.fast, info.s, info.a])
  supportRows.get(b).push([a, info.romantic, info.fast, info.s, info.a])
}

const classLines = classes
  .map((c) => {
    const dlc = c.id >= DLC_CLASS_MIN && c.id <= DLC_CLASS_MAX ? ', dlc: true' : ''
    return `  ${c.id}: { name: ${JSON.stringify(c.name)}, tier: ${JSON.stringify(c.tier)}, baseStats: ${JSON.stringify(c.baseStats)}, growths: ${JSON.stringify(c.growths)}, caps: ${JSON.stringify(c.caps)}, pairUp: ${JSON.stringify(c.pairUp)}, skills: ${JSON.stringify(c.skills)}, promotesFrom: ${JSON.stringify(c.promotesFrom)}, promotesTo: ${JSON.stringify(c.promotesTo)}${dlc} },`
  })
  .join('\n')

const unitLines = units
  .map((u) => {
    const dlc = DLC_UNITS.has(u.id) ? ', dlc: true' : ''
    const corrin = u.isCorrin ? ', isCorrin: true' : ''
    const fixed = u.fixedParent ? `, fixedParent: ${JSON.stringify(u.fixedParent)}` : ''
    const personal = `[${u.personalSkills.birthright ?? 0},${u.personalSkills.conquest ?? 0},${u.personalSkills.revelation ?? 0}]`
    return `  ${JSON.stringify(u.id)}: { name: ${JSON.stringify(u.name)}, gender: ${JSON.stringify(u.gender)}, growths: ${JSON.stringify(u.growths)}, baseStats: ${JSON.stringify(u.baseStats)}, capMods: ${JSON.stringify(u.capMods)}, classes: ${JSON.stringify(u.classes)}, reclasses: ${JSON.stringify(u.reclasses)}, personal: ${personal}${corrin}${fixed}${dlc} },`
  })
  .join('\n')

const skillLines = skills.map((s) => `  ${s.id}: ${JSON.stringify(s.name)},`).join('\n')

const supportEntries = [...supportRows.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([id, rows]) => {
    const body = rows.map((r) => JSON.stringify(r)).join(', ')
    return `  ${JSON.stringify(id)}: [${body}],`
  })
  .join('\n')

const out = `/* GENERATED by scripts/gen-game-tables.mjs from src/data/packs/ugf-2.5.2 — do not hand-edit. */
import type { ClassTier } from '../data/types'

export interface ProtoClassRow {
  name: string
  tier: ClassTier
  baseStats: number[]
  growths: number[]
  caps: number[]
  pairUp: number[]
  skills: number[]
  promotesFrom: number[]
  promotesTo: number[]
  dlc?: true
}

export interface ProtoUnitRow {
  name: string
  gender: 'male' | 'female'
  growths: number[]
  baseStats: number[]
  capMods: number[]
  classes: number[]
  reclasses: number[]
  /** Personal skill id per route: [birthright, conquest, revelation]. */
  personal: number[]
  isCorrin?: true
  fixedParent?: string
  dlc?: true
}

/** Support row: [partnerId, romantic, fast, hasS, hasA]. */
export type ProtoSupportRow = [string, boolean, boolean, boolean, boolean]

export const PROTO_CLASSES: Record<number, ProtoClassRow> = {
${classLines}
}

export const PROTO_UNITS: Record<string, ProtoUnitRow> = {
${unitLines}
}

export const PROTO_SKILLS: Record<number, string> = {
${skillLines}
}

/** Support graph subset for the plan-aware units; real UGF edges. */
export const PROTO_SUPPORTS: Record<string, ProtoSupportRow[]> = {
${supportEntries}
}
`

writeFileSync(join(root, 'src', 'prototype', 'gameTables.ts'), out)
console.log(`wrote src/prototype/gameTables.ts (${classes.length} classes, ${units.length} units, ${supportRows.size} support entries)`)
